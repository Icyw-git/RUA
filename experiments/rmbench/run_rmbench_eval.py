import argparse
import json
import os
import subprocess
import sys
from pathlib import Path


ADAPTER_MARKER = "Auto-generated by WLA experiments/rmbench adapter."
ADAPTER_FILES = ("deploy_policy.py", "rmbench_utils.py")
ADAPTER_OPTION_KEYS = (
    "model_id",
    "checkpoints_dir",
    "norm_file_path",
    "unnorm_key",
    "control_mode",
    "target_image_size",
    "vae_downsample_f",
    "max_state_dim",
    "original_action_dim",
    "primary_image_size",
    "auxiliary_image_size",
    "action_chunk_size",
    "strip_world_model",
    "dtype",
)


def str_to_bool(value):
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"1", "true", "yes", "y", "on"}


def optional_str(value):
    if value in {None, "", "None", "none", "null"}:
        return None
    return str(value)


def default_wla_root() -> Path:
    return Path(__file__).resolve().parents[2]


def default_rmbench_root(wla_root: Path) -> Path:
    return wla_root / "RMBench"


def write_generated_file(path: Path, content: str, *, overwrite: bool):
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if existing == content:
            return
        if ADAPTER_MARKER not in existing and not overwrite:
            raise RuntimeError(
                f"Refusing to overwrite existing non-generated file: {path}\n"
                "Use --overwrite_policy_adapter true or choose another --policy_name."
            )
    path.write_text(content, encoding="utf-8")


def adapter_options(args) -> dict:
    return {key: getattr(args, key) for key in ADAPTER_OPTION_KEYS}


def stage_policy_adapter(args, wla_root: Path, rmbench_root: Path):
    adapter_root = Path(__file__).resolve().parent
    policy_dir = rmbench_root / "policy" / args.policy_name
    policy_dir.mkdir(parents=True, exist_ok=True)

    for filename in ADAPTER_FILES:
        source = adapter_root / filename
        target = policy_dir / filename
        write_generated_file(
            target,
            source.read_text(encoding="utf-8"),
            overwrite=args.overwrite_policy_adapter,
        )

    init_content = "from .deploy_policy import *\n"
    write_generated_file(policy_dir / "__init__.py", init_content, overwrite=True)

    config = {
        "policy_name": None,
        "task_name": None,
        "task_config": None,
        "ckpt_setting": None,
        "seed": None,
        "instruction_type": args.instruction_type,
        "wla_root": str(wla_root),
        **adapter_options(args),
    }
    config_text = "# Auto-generated by WLA experiments/rmbench adapter.\n"
    config_text += json.dumps(config, indent=2)
    config_text += "\n"
    write_generated_file(policy_dir / "deploy_policy.yml", config_text, overwrite=True)

    return policy_dir


def validate_rmbench_root(rmbench_root: Path):
    eval_policy = rmbench_root / "script" / "eval_policy.py"
    if not eval_policy.is_file():
        raise FileNotFoundError(
            f"RMBench checkout not found at {rmbench_root}. "
            "Clone RMBench into WLA/RMBench or pass --rmbench_root."
        )


def resolve_existing_file(path_value: str, wla_root: Path, rmbench_root: Path) -> Path:
    path = Path(path_value).expanduser()
    if path.is_absolute():
        return path

    wla_candidate = wla_root / path
    if wla_candidate.exists():
        return wla_candidate

    rmbench_candidate = rmbench_root / path
    if rmbench_candidate.exists():
        return rmbench_candidate

    return wla_candidate


def validate_norm_stats(args, wla_root: Path, rmbench_root: Path):
    if not args.norm_file_path or not args.unnorm_key:
        return

    norm_file_path = resolve_existing_file(args.norm_file_path, wla_root, rmbench_root)
    if not norm_file_path.is_file():
        raise FileNotFoundError(
            f"Normalization file not found: {norm_file_path}. "
            "Set NORM_FILE_PATH to the norm_stats.json used during training."
        )

    with norm_file_path.open("r", encoding="utf-8") as f:
        norm_stats = json.load(f)
    if args.unnorm_key not in norm_stats:
        available = ", ".join(sorted(norm_stats.keys()))
        raise ValueError(
            f"Normalization key '{args.unnorm_key}' not found in {norm_file_path}. "
            "Set NORM_FILE_PATH and UNNORM_KEY to match the training config. "
            f"Available keys: {available}"
        )


def build_eval_command(args):
    command = [
        sys.executable,
        "script/eval_policy.py",
        "--config",
        f"policy/{args.policy_name}/deploy_policy.yml",
        "--overrides",
        "--task_name",
        args.task_name,
        "--task_config",
        args.task_config,
        "--ckpt_setting",
        args.ckpt_setting,
        "--seed",
        str(args.seed),
        "--policy_name",
        args.policy_name,
        "--instruction_type",
        args.instruction_type,
    ]

    for key, value in adapter_options(args).items():
        if value is None:
            continue
        command.extend([f"--{key}", str(value)])

    command.extend(args.extra_overrides)
    return command


def parse_args():
    wla_root = default_wla_root()
    parser = argparse.ArgumentParser()
    parser.add_argument("--rmbench_root", default=os.environ.get("RMBENCH_ROOT", str(default_rmbench_root(wla_root))))
    parser.add_argument("--policy_name", default=os.environ.get("RMBENCH_POLICY_NAME", "WLA"))
    parser.add_argument("--task_name", required=True)
    parser.add_argument("--task_config", required=True)
    parser.add_argument("--ckpt_setting", required=True)
    parser.add_argument("--seed", required=True, type=int)
    parser.add_argument("--instruction_type", default=os.environ.get("INSTRUCTION_TYPE", "unseen"))
    parser.add_argument("--model_id", default=os.environ.get("MODEL_ID"))
    parser.add_argument("--checkpoints_dir", default=os.environ.get("CHECKPOINTS_DIR"))
    parser.add_argument(
        "--norm_file_path",
        default=os.environ.get(
            "NORM_FILE_PATH",
            os.environ.get("MANTIS_NORM_STATS_PATH", "configs/norm_stats.json"),
        ),
    )
    parser.add_argument("--unnorm_key", default=os.environ.get("UNNORM_KEY", os.environ.get("MANTIS_NORM_KEY")))
    parser.add_argument("--control_mode", choices=("eef", "joint"), default=os.environ.get("CONTROL_MODE", "joint"))
    parser.add_argument("--target_image_size", type=int, default=int(os.environ.get("TARGET_IMAGE_SIZE", 512)))
    parser.add_argument("--vae_downsample_f", type=int, default=int(os.environ.get("VAE_DOWNSAMPLE_F", 32)))
    parser.add_argument("--max_state_dim", type=int, default=optional_str(os.environ.get("MAX_STATE_DIM")))
    parser.add_argument("--original_action_dim", type=int, default=optional_str(os.environ.get("ORIGINAL_ACTION_DIM")))
    parser.add_argument("--primary_image_size", type=int, default=int(os.environ.get("PRIMARY_IMAGE_SIZE", 256)))
    parser.add_argument("--auxiliary_image_size", type=int, default=int(os.environ.get("AUXILIARY_IMAGE_SIZE", 256)))
    parser.add_argument("--action_chunk_size", type=int, default=optional_str(os.environ.get("ACTION_CHUNK_SIZE")))
    parser.add_argument("--strip_world_model", type=str_to_bool, default=str_to_bool(os.environ.get("STRIP_WORLD_MODEL", "true")))
    parser.add_argument("--dtype", default=os.environ.get("WLA_DTYPE", "bfloat16"))
    parser.add_argument("--overwrite_policy_adapter", type=str_to_bool, default=False)
    parser.add_argument("--extra_overrides", nargs=argparse.REMAINDER, default=[])
    return parser.parse_args()


def main():
    args = parse_args()
    if not args.model_id:
        raise ValueError("model_id is required. Pass it as run_rmbench_eval.sh arg 6, MODEL_ID, or --model_id.")
    for key in ("unnorm_key", "max_state_dim", "original_action_dim"):
        if getattr(args, key) in {None, "", "None", "none", "null"}:
            raise ValueError(f"{key} is required. Set it in run_rmbench_eval.sh or pass --{key}.")

    wla_root = default_wla_root()
    rmbench_root = Path(args.rmbench_root).expanduser().resolve()
    validate_rmbench_root(rmbench_root)
    validate_norm_stats(args, wla_root, rmbench_root)

    policy_dir = stage_policy_adapter(args, wla_root, rmbench_root)
    print(f"Staged WLA RMBench policy adapter at: {policy_dir}")

    env = os.environ.copy()
    env["WLA_ROOT"] = str(wla_root)

    command = build_eval_command(args)
    print("Running RMBench evaluation:")
    print(" ".join(command))
    subprocess.run(command, cwd=str(rmbench_root), env=env, check=True)


if __name__ == "__main__":
    try:
        main()
    except (FileNotFoundError, RuntimeError, ValueError) as exc:
        raise SystemExit(f"ERROR: {exc}") from None
